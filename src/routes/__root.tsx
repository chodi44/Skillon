function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  return (
    <QueryClientProvider client={queryClient}>
      <ThemeProvider>
        <AuthProvider>
          <SkillonProvider>
            <Outlet />
            <AlarmRunner />
            <RegisterSW />
          </SkillonProvider>

        </AuthProvider>
      </ThemeProvider>
    </QueryClientProvider>
  );
}
